// Builds the Media > Presentation decks from the app's own words, pictures and teaching scenes.
// One deck per word group plus a full-topic deck. Writes site/dist/presentations/decks.js (the in-app
// presenter reads it) and a deck plan JSON for scripts/build-presentations-pptx.py (the PowerPoint files).
// Usage: node scripts/build-presentations.mjs
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import vm from 'node:vm';

const root = new URL('../', import.meta.url);
const file = name => new URL(name, root);
const context = vm.createContext({});
for (const name of ['curriculum.js', 'standard-data.js', 'images/teaching-scenes/library.js'])
  vm.runInContext(await readFile(file(`site/dist/${name}`), 'utf8'), context, {filename: name});
const app = await readFile(file('site/dist/app.js'), 'utf8');
const boundary = app.indexOf('const classroom = new TransportClassroom(');
if (boundary < 0) throw Error('Review the presentation adapter: app content boundary changed.');
vm.runInContext(app.slice(0, boundary) + '\nglobalThis.words=transportWords;', context, {filename: 'app-content.js'});

const {categories, teachingCategories} = context.TransportStandard;
const library = context.TransportSceneLibrary;
const entry = new Map(library.entries.map(e => [e.id, e]));
const groups = [...categories.filter(g => g.id !== 'all'), ...teachingCategories.filter(g => !categories.some(c => c.id === g.id))];
const words = context.words.map(w => ({id: w.id, name: w.name, meaning: w.definition || entry.get(w.id)?.definition || '', example: w.example || entry.get(w.id)?.example || '', image: w.image, group: w.category}));
const cover = id => `images/classroom/cover-${id}.webp`;

// A scene belongs to the group most of its labelled words come from.
const sceneGroup = scene => {
  const count = {};
  for (const id of scene.entryIds) { const g = words.find(w => w.id === id)?.group; if (g) count[g] = (count[g] || 0) + 1; }
  return Object.entries(count).sort((a, b) => b[1] - a[1])[0]?.[0];
};
const scenes = library.scenes.map(s => ({id: s.id, title: s.title, image: `images/teaching-scenes/${s.image}`, alt: s.alt,
  labels: (s.labels || []).map(([name, text]) => [name, text]), group: sceneGroup(s)}));

const chunk = (list, size) => Array.from({length: Math.ceil(list.length / size)}, (_, i) => list.slice(i * size, i * size + size));
function groupSlides(group, list) {
  const slides = [{type: 'section', title: group.label, subtitle: `${list.length} words`, image: cover(group.id)}];
  for (const part of chunk(list, 12)) slides.push({type: 'grid', title: 'In this lesson', items: part.map(w => ({name: w.name, image: w.image}))});
  for (const w of list) slides.push({type: 'word', id: w.id, name: w.name, meaning: w.meaning, example: w.example, image: w.image});
  for (const s of scenes.filter(s => s.group === group.id)) slides.push({type: 'scene', title: s.title, image: s.image, alt: s.alt, labels: s.labels.slice(0, 6)});
  // Name-them check: pictures first, then the same pictures with names.
  const quiz = list.slice().sort((a, b) => a.id.localeCompare(b.id)).filter((_, i) => i % Math.max(1, Math.floor(list.length / 6)) === 0).slice(0, 6);
  slides.push({type: 'quiz', title: 'Can you name them?', items: quiz.map(w => ({image: w.image}))});
  slides.push({type: 'answers', title: 'Did you get them?', items: quiz.map(w => ({name: w.name, image: w.image}))});
  return slides;
}

const decks = [];
const end = {type: 'end', title: 'Well done!', subtitle: 'You learned all about transport.', image: 'images/classroom/completion.webp'};
for (const group of groups) {
  const list = words.filter(w => w.group === group.id);
  if (!list.length) continue;
  const slides = [{type: 'title', title: group.label, subtitle: 'Transport Town', image: cover(group.id)}, ...groupSlides(group, list).slice(1), {...end, subtitle: `You learned about ${group.label.toLowerCase()}.`}];
  decks.push({id: group.id, title: group.label, image: cover(group.id), wordCount: list.length, slides});
}
const all = [{type: 'title', title: 'All about transport', subtitle: 'Transport Town', image: cover('all')}];
for (const group of groups) { const list = words.filter(w => w.group === group.id); if (list.length) all.push(...groupSlides(group, list)); }
all.push(end);
decks.unshift({id: 'all', title: 'All about transport', image: cover('all'), wordCount: words.length, slides: all});
for (const deck of decks) { deck.slideCount = deck.slides.length; deck.pptx = `presentations/transport-presentation-${deck.id}.pptx`; }

await mkdir(file('site/dist/presentations/'), {recursive: true});
await writeFile(file('site/dist/presentations/decks.js'), `// Generated by scripts/build-presentations.mjs.\nglobalThis.TransportPresentations = ${JSON.stringify(decks)};\n`);
await writeFile(file('artwork/presentations-plan.json'), JSON.stringify(decks, null, 1) + '\n');
console.log(decks.map(d => `${d.id}: ${d.slideCount} slides`).join('\n'));
