import { readFile, readdir, writeFile } from 'node:fs/promises';
import { readTransportContent } from './content-source.mjs';

const root = new URL('../', import.meta.url);
const file = name => new URL(name, root);
const data = JSON.parse(await readFile(file('content/teaching-scenes.json'), 'utf8'));
const curriculum = JSON.parse(await readFile(file('docs/content/CURRICULUM-PLAN.json'), 'utf8'));
const { entries: originals } = await readTransportContent(root);
const excluded = new Set(['action.balance', 'action.start', 'safety.speed-limit', 'safety.visibility', 'safety.safe-distance']);
const additional = curriculum.proposals.filter(word => !excluded.has(word.id)).map(word => {
  const edits = data.wordEdits[word.id] || {};
  return { ...word, ...edits, name: edits.name || word.label };
});
const words = new Map([...originals, ...additional].map(word => [word.id, word]));
const mapped = [...data.pilotIds, ...data.scenes.flatMap(scene => scene.targets.map(target => target[0]))];
if (words.size !== 121 || mapped.length !== 121 || new Set(mapped).size !== 121 || mapped.some(id => !words.has(id))) {
  throw new Error('The approved teaching library must map all 121 distinct vocabulary entries.');
}

function makePath(region) {
  if (Array.isArray(region[0])) return region.map(makePath).join(' ');
  if (region.length === 4) {
    const [left, top, right, bottom] = region;
    return `M${left} ${top}H${right}V${bottom}H${left}Z`;
  }
  if (region.length < 6 || region.length % 2 !== 0) throw new Error('Invalid highlight coordinates');
  return 'M' + region.join(' ') + 'Z';
}

const scenes = [];
const installed = new Set(data.pilotIds);
for (const scene of data.scenes) {
  // Dimensions come from the full-size original; the app ships the web-sized JPEG copy.
  const image = scene.id + '.jpg';
  const path = file('artwork/originals/teaching-scenes/' + scene.id + '.png');
  let artwork;
  try {
    artwork = await readFile(path);
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
    continue;
  }
  const entryIds = scene.targets.map(target => target[0]);
  const labels = scene.targets.map(([id, region, kind]) => {
    const word = words.get(id);
    installed.add(id);
    const label = word.name[0].toUpperCase() + word.name.slice(1);
    return [label, word.definition, makePath(region), ...(kind ? [kind] : [])];
  });
  if (artwork.toString('ascii',12,16) !== 'IHDR') throw new Error('Invalid PNG: ' + image);
  scenes.push({ title: scene.title, image, alt: scene.alt, width: artwork.readUInt32BE(16), height: artwork.readUInt32BE(20), viewBox: '0 0 1000 1000', entryIds, labels, inscriptions: scene.inscriptions });
}
const artFolder = file('site/dist/images/vocabulary/');
let individualFiles;
try {
  individualFiles = await readdir(artFolder, { withFileTypes: true });
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
  individualFiles = [];
}
const individualIds = individualFiles
  .filter(entry => entry.isFile() && entry.name.endsWith('.png'))
  .map(entry => entry.name.slice(0, -4))
  .filter(id => words.has(id))
  .sort();
const individualImages = Object.fromEntries(individualIds.map(id => [id, `images/vocabulary/${id}.png`]));

const entries = additional.filter(word => installed.has(word.id) || individualImages[word.id]).map(word => {
  const category = word.kind === 'vehicle' ? word.zone || ({ water: 'water', air: 'space' })[word.lessons[0]] || 'land' : word.kind;
  const vehicle = word.kind === 'vehicle';
  // Every installed word joins the picture games. Sort membership is still decided by the authored rules.
  return {
    id: word.id, name: word.name, level: word.level, aliases: word.aliases,
    lessons: word.lessons, collections: word.collections, category, definition: word.definition,
    example: word.example, image: individualImages[word.id] || '', alt: word.alt || `A picture showing ${word.name}.`, pictureGroup: word.id, silhouetteEligible: false,
    eligibility: { learn: true, sort: vehicle, identify: true, hangman: true, flip: true, wheel: true, detective: true, sound: false },
  };
});
const library = { entries, scenes, individualIds, individualImages };
await writeFile(file('site/dist/images/teaching-scenes/library.js'), '// Generated by scripts/build-teaching-library.mjs.\nglobalThis.TransportSceneLibrary = ' + JSON.stringify(library, null, 2) + ';\n');
console.log(`Registered ${individualIds.length}/121 individual teaching pictures and ${scenes.length} illustrated scenes.`);
